/* ---------- text generators ---------- */
// Makes a title for a category from its word lists: subject + verb + object + tail.
function makeTitle(category) {
  const v = VOCAB[category];
  return `${pick(v.subjects)} ${pick(v.verbs)} ${pick(v.objects)} ${pick(TAILS)}`;
}

// Makes a summary of one or two random sentences (two if the title is short). It is cut to 290 characters to fit the 300 limit.
function makeSummary(title) {
  return `${pick(SENTENCES)} ${title.length < 80 ? pick(SENTENCES) : ''}`.trim().slice(0, 290);
}

// Makes one paragraph: 3 to 5 random sentences joined together.
function makeParagraph() {
  return Array.from({ length: between(3, 5) }, () => pick(SENTENCES)).join(' ');
}

// Makes the article text: 4 to 7 paragraphs separated by a blank line (the same format the editor page uses).
function makeContent() {
  return Array.from({ length: between(4, 7) }, makeParagraph).join('\n\n');
}

// Gives the address of a placeholder picture for an article (we don't download real images).
function imageFor(category, label) {
  return `/placeholder/${category}/${label}.svg`;
}

/** Builds an edited copy of a version (used for post-publication updates). */
// Takes an article version and returns a slightly changed copy: one paragraph rewritten, sometimes a new paragraph at the end,
// sometimes a new title ending like "(updated 2)", sometimes a new summary. This is what makes the review diff show real changes.
function editVersion(content, round) {
  const paragraphs = content.content.split('\n\n');
  const idx = between(0, paragraphs.length - 1);
  paragraphs[idx] = makeParagraph();
  if (chance(0.6)) paragraphs.push(makeParagraph());
  return {
    ...content,
    title: chance(0.4)
      ? `${content.title.replace(/ \((updated \d+|revised)\)$/, '')} (${typeof round === 'number' ? `updated ${round}` : 'revised'})`.slice(0, 150)
      : content.title,
    summary: chance(0.5) ? makeSummary(content.title) : content.summary,
    content: paragraphs.join('\n\n'),
  };
}

/* ---------- view statistics ---------- */
// Day/night factor between 0.1 and 1 for a given hour: fewest views around midnight, most around midday (UTC time).
const diurnal = (date) => 0.55 + 0.45 * Math.sin(((date.getUTCHours() - 6) / 24) * 2 * Math.PI); // quiet at night

/**
 * Hourly view counts between `from` and `now`. Interest decays with age, and every published update gives
 * the article a fresh boost (so the chart shows a clear before / after difference).
 */
// Goes hour by hour from the publish time until now and works out how many views each hour got.
// The rate starts at baseRate, shrinks over time, jumps up after every update, is lowered at night, and gets a bit of randomness.
// Returns the hourly documents (one per hour that had views) and the total number of views.
// Important: views are stored as one number per hour ("buckets") instead of one document per view, so the database stays small and the chart is fast.
function buildBuckets(articleId, from, now, baseRate, updateTimes, boost) {
  const out = [];
  const start = Math.floor(from.getTime() / HOUR) * HOUR;
  const end = Math.floor(now.getTime() / HOUR) * HOUR;
  let total = 0;
  for (let t = start; t <= end; t += HOUR) {
    const hoursSincePublish = (t - from.getTime()) / HOUR;
    let rate = baseRate * Math.exp(-hoursSincePublish / 90);
    // For every update that already happened, add an extra boost that fades away with time.
    updateTimes.forEach((u) => {
      const since = (t - u.getTime()) / HOUR;
      if (since >= 0) rate += baseRate * boost * Math.exp(-since / 40);
    });
    rate *= diurnal(new Date(t));
    const count = Math.round(rate * (0.7 + rand() * 0.6));
    if (count > 0) {
      out.push({ article: articleId, hour: new Date(t), count });
      total += count;
    }
  }
  return { buckets: out, total };
}

