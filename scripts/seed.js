// The whole seed: connect, delete the old data, create users, articles, view statistics and comments, print a summary.
// Important: it DELETES the old users, articles, comments, stats and sessions first, so only run it on a demo database.
async function main() {
  if (!config.seedPassword || config.seedPassword.length < 6) {
    console.error('Set SEED_PASSWORD (at least 6 characters) in your .env file first.');
    process.exit(1);
  }

  const started = Date.now();
  await mongoose.connect(config.mongoUri);
  console.log(`Connected to ${mongoose.connection.name}. Clearing old data...`);

  await Promise.all([
    User.deleteMany({}),
    Article.deleteMany({}),
    Comment.deleteMany({}),
    ViewStat.deleteMany({}),
    ViewedLog.deleteMany({}),
    mongoose.connection.collection('sessions').deleteMany({}),
  ]);
  await Promise.all([User.init(), Article.init(), Comment.init(), ViewStat.init(), ViewedLog.init()]);

  /* ---- users ---- */
  // Important: the password is never stored as plain text, only as a hash (made by our authService). All seed users share one hash.
  const passwordHash = await hashPassword(config.seedPassword);
  const editor = await User.create({ username: 'editor', displayName: 'Rachel Editor', role: 'editor', passwordHash });
  const reporters = await User.insertMany(
    REPORTERS.map(([username, displayName]) => ({ username, displayName, role: 'reporter', passwordHash }))
  );

  /* ---- plan the article states ---- */
  // A list with one entry per article saying which workflow state it will be in:
  // "published" = live only; "published+X" = live and also an update in state X; "new+X" = never published, only a draft in state X.
  // Important: this makes sure all 600 articles are spread over every workflow state (380 + 40 + 15 + 10 + 55 + 55 + 45 = 600).
  const plan = [
    ...Array(380).fill('published'),
    ...Array(40).fill('published+pending'),
    ...Array(15).fill('published+preparation'),
    ...Array(10).fill('published+returned'),
    ...Array(55).fill('new+preparation'),
    ...Array(55).fill('new+pending'),
    ...Array(45).fill('new+returned'),
  ].slice(0, TOTAL_ARTICLES);
  // shuffle (Fisher-Yates with the seeded generator)
  // Mix the list so the states are not in blocks. We use our seeded generator, so the mix is the same every run.
  for (let i = plan.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [plan[i], plan[j]] = [plan[j], plan[i]];
  }

  // now = the moment the seed runs. articles / bucketDocs = everything we will insert at the end.
  // featured = the demo articles with many updates (printed at the end for the analytics demo).
  const now = new Date();
  const articles = [];
  const bucketDocs = [];
  const featured = [];
  let publishedIndex = 0;

  // Build one article document for every entry in the plan.
  plan.forEach((state, index) => {
    // Categories are used in turn, so every category gets about the same number of articles.
    const category = CATEGORIES[index % CATEGORIES.length];
    const author = pick(reporters);
    const title = makeTitle(category);
    const base = {
      title,
      summary: makeSummary(title),
      content: makeContent(),
      category,
      image: imageFor(category, `${index}-${hex(4)}`),
    };
    // The article document. "live" = the published version, "revision" = the working copy (draft / update waiting). Both are filled in below.
    const doc = { _id: new mongoose.Types.ObjectId(), author: author._id, viewCount: 0, publishHistory: [], reviewHistory: [] };
    // Small helper: one entry of the review history (who did what and when), done by the reporter or by the editor.
    const MIN = 60 * 1000;
    const rev = (at, action, note) => ({
      at,
      by: action === 'submitted' ? author._id : editor._id,
      byName: action === 'submitted' ? author.displayName : editor.displayName,
      role: action === 'submitted' ? 'reporter' : 'editor',
      action,
      note: note || '',
    });
    // History for a version that is waiting or was returned. Returned ones often went through an earlier round,
    // so the reporter and the editor can see MORE than just the latest note.
    const addRevisionHistory = (t, status, latestNote) => {
      if (status === 'in_preparation') return; // still being written: nothing was submitted yet
      if (status === 'returned' && chance(0.5)) {
        doc.reviewHistory.push(rev(new Date(t.getTime() - 40 * 60 * MIN), 'submitted'));
        doc.reviewHistory.push(rev(new Date(t.getTime() - 36 * 60 * MIN), 'returned', pick(EDITOR_NOTES)));
      }
      doc.reviewHistory.push(rev(new Date(t.getTime() - (status === 'returned' ? 20 : 0) * 60 * MIN - 5 * MIN), 'submitted'));
      if (status === 'returned') doc.reviewHistory.push(rev(t, 'returned', latestNote));
    };

    const hasLive = state.startsWith('published');
    if (hasLive) {
      // Published branch: create the live version, its publish history, its view numbers, and maybe a waiting update.
      publishedIndex++;
      // The first 25 published articles are the "featured demo" ones: many updates, lots of views.
      const isFeatured = publishedIndex <= 25;
      const updates = isFeatured ? between(2, 5) : chance(0.2) ? 1 : 0;

      // Featured demo articles are 9-13 days old (room for several updates). All others are spread over the last
      // ~6 weeks, skewed towards recent days, with random hours and minutes, so the feed shows many different dates.
      const ageMs = isFeatured ? (9 + rand() * 4.5) * DAY : Math.pow(rand(), 1.35) * 42 * DAY + (60 + between(0, 120)) * 60 * 1000;
      const firstAt = new Date(now.getTime() - ageMs);
      let live = base;
      const history = [{ at: firstAt, by: editor._id, kind: 'initial' }];
      const updateTimes = [];
      let cursor = firstAt.getTime();
      // Create the published updates one after the other. Each one is 1-2 days (featured) or 1 day after the previous one,
      // and we stop if the date would be too close to "now" or not after the last one.
      for (let u = 1; u <= updates; u++) {
        // spread updates over the following days, at clearly visible times (the first is exactly 14:00 UTC)
        const gapDays = isFeatured ? between(1, 2) : 1;
        cursor += gapDays * DAY;
        if (cursor > now.getTime() - 6 * HOUR) break;
        const at = new Date(cursor);
        at.setUTCMinutes(u === 1 ? 0 : between(0, 59), 0, 0);
        if (u === 1) at.setUTCHours(14);
        if (at.getTime() > now.getTime() - 3 * HOUR || at.getTime() <= history[history.length - 1].at.getTime()) break;
        live = editVersion(live, u);
        history.push({ at, by: editor._id, kind: 'update' });
        updateTimes.push(at);
      }

      doc.live = { ...live, publishedAt: firstAt };
      doc.publishHistory = history;
      // Review history: before every publication the reporter submitted it and the editor approved it.
      // Some first publications also had a round of corrections first (submitted -> returned with a note -> submitted again).
      history.forEach((h, i) => {
        if (i === 0 && chance(0.3)) {
          doc.reviewHistory.push(rev(new Date(h.at.getTime() - 30 * 60 * MIN), 'submitted'));
          doc.reviewHistory.push(rev(new Date(h.at.getTime() - 26 * 60 * MIN), 'returned', pick(EDITOR_NOTES)));
        }
        doc.reviewHistory.push(rev(new Date(h.at.getTime() - between(30, 600) * MIN), 'submitted'));
        doc.reviewHistory.push(rev(h.at, 'approved'));
      });
      doc.createdAt = new Date(firstAt.getTime() - between(2, 30) * HOUR);
      doc.updatedAt = history[history.length - 1].at;

      // Views per hour at the start: featured articles get many, a few others get a medium number, most get few.
      const baseRate = isFeatured ? between(14, 26) : chance(0.1) ? between(8, 20) : between(1, 6);
      const { buckets, total } = buildBuckets(doc._id, firstAt, now, baseRate, updateTimes, isFeatured ? 2.2 : 1.2);
      bucketDocs.push(...buckets);
      doc.viewCount = total;
      if (isFeatured) featured.push({ id: String(doc._id), title: live.title, updates: updateTimes.length });

      // If the plan says "published+something", the article also has a newer version waiting (pending / in preparation / returned).
      if (state !== 'published') {
        const status = state.split('+')[1];
        const revisionStatus = { pending: 'pending_approval', preparation: 'in_preparation', returned: 'returned' }[status];
        const edited = editVersion(live, 'next');
        doc.revision = {
          ...edited,
          status: revisionStatus,
          editorNote: revisionStatus === 'returned' ? pick(EDITOR_NOTES) : '',
          updatedAt: new Date(now.getTime() - between(1, 48) * HOUR - jitter()),
        };
        doc.updatedAt = doc.revision.updatedAt;
        addRevisionHistory(doc.revision.updatedAt, revisionStatus, doc.revision.editorNote);
      }
    } else {
      // Brand-new article that was never published: it only has a working copy (revision), no live version and no views.
      const status = state.split('+')[1];
      const revisionStatus = { pending: 'pending_approval', preparation: 'in_preparation', returned: 'returned' }[status];
      const updatedAt = new Date(now.getTime() - between(1, 240) * HOUR - jitter());
      // an early draft may still be incomplete
      const draft = revisionStatus === 'in_preparation' && chance(0.3) ? { ...base, image: '', summary: '' } : base;
      doc.revision = {
        ...draft,
        status: revisionStatus,
        editorNote: revisionStatus === 'returned' ? pick(EDITOR_NOTES) : '',
        updatedAt,
      };
      doc.createdAt = new Date(updatedAt.getTime() - between(1, 72) * HOUR);
      doc.updatedAt = updatedAt;
      addRevisionHistory(updatedAt, revisionStatus, doc.revision.editorNote);
    }
    // Keep the review history in time order (oldest first), like the real application does.
    doc.reviewHistory.sort((a, b) => a.at - b.at);
    articles.push(doc);
  });

  /* ---- write articles ---- */
  // Important: we insert through the raw MongoDB collection (not Article.create) so our own dates (createdAt, updatedAt) are kept
  // and all 600 articles go in with one fast call.
  console.log(`Creating ${articles.length} articles...`);
  await Article.collection.insertMany(articles.map((a) => ({ ...a, __v: 0 })));

  /* ---- view statistics (raw insert in chunks: tens of thousands of small documents) ---- */
  console.log(`Creating ${bucketDocs.length} hourly view buckets...`);
  // Insert 5000 documents at a time, so we don't send one huge request.
  for (let i = 0; i < bucketDocs.length; i += 5000) {
    await ViewStat.collection.insertMany(bucketDocs.slice(i, i + 5000), { ordered: false });
  }

  /* ---- comments ---- */
  // Only published articles get comments. Popular ones (over 800 views) get more. Each comment is dated after the publish time and never in the future.
  const comments = [];
  articles
    .filter((a) => a.live)
    .forEach((a) => {
      const n = a.viewCount > 800 ? between(6, 16) : chance(0.7) ? between(1, 6) : 0;
      for (let i = 0; i < n; i++) {
        const createdAt = new Date(a.live.publishedAt.getTime() + between(1, 200) * HOUR + jitter());
        if (createdAt > now) continue;
        comments.push({
          article: a._id,
          authorName: pick(COMMENT_NAMES),
          text: pick(COMMENT_TEXTS),
          deviceId: `seed-${hex(12)}`,
          ip: `10.0.${between(0, 255)}.${between(1, 254)}`,
          createdAt,
          updatedAt: createdAt,
          __v: 0,
        });
      }
    });
  console.log(`Creating ${comments.length} comments...`);
  if (comments.length) await Comment.collection.insertMany(comments);

  /* ---- summary ---- */
  // Count the articles in each state, so we can print a table and check that every state really exists.
  const counts = {
    published: articles.filter((a) => a.live && !a.revision).length,
    'published, update pending approval': articles.filter((a) => a.live && a.revision && a.revision.status === 'pending_approval').length,
    'published, update in preparation': articles.filter((a) => a.live && a.revision && a.revision.status === 'in_preparation').length,
    'published, update returned': articles.filter((a) => a.live && a.revision && a.revision.status === 'returned').length,
    'new, in preparation': articles.filter((a) => !a.live && a.revision.status === 'in_preparation').length,
    'new, awaiting approval': articles.filter((a) => !a.live && a.revision.status === 'pending_approval').length,
    'new, returned': articles.filter((a) => !a.live && a.revision.status === 'returned').length,
  };
  console.log('\nArticles by state:');
  // Print one line per state: the number, then the name.
  Object.entries(counts).forEach(([k, v]) => console.log(`  ${String(v).padStart(4)}  ${k}`));

  console.log('\nLogin accounts (password = SEED_PASSWORD from your .env):');
  console.log('  editor      ->  editor');
  REPORTERS.forEach(([u]) => console.log(`  reporter    ->  ${u}`));

  console.log('\nGood articles for the Impact Analytics demo (several updates, lots of views):');
  featured.slice(0, 5).forEach((f) => console.log(`  ${f.updates} update(s)  /editor/analytics?article=${f.id}   ${f.title.slice(0, 60)}`));

  console.log(`\nDone in ${((Date.now() - started) / 1000).toFixed(1)}s.`);
  await mongoose.disconnect();
}

// Start the seed. If anything fails, print the error, close the database connection and exit with an error code.
main().catch(async (err) => {
  console.error('Seeding failed:', err);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
