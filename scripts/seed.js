// Time units in milliseconds (JavaScript dates work in milliseconds).
const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
/** Random seconds-level offset so timestamps are not all on the same minute. */
// Gives a random number of milliseconds between 0 and just under 1 hour. We add it to times so they don't all look the same.
const jitter = () => between(0, 3599) * 1000;
// How many articles the seed creates.
const TOTAL_ARTICLES = 600;

/* ---------- deterministic random numbers (same data on every run, relative to "now") ---------- */
// A small random number generator (mulberry32). You give it a starting number (the seed) and it returns a function.
// Each call of that function gives the next "random" number between 0 and 1.
// Important: with the same seed you get the same numbers in the same order, so the demo data is the same on every run
// (Math.random() would give different data every time).
function mulberry32(seed) {
  let a = seed >>> 0;
  // The function we return. It changes the hidden number "a" with some bit maths and gives back a value from 0 up to (not including) 1.
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
// Our one random generator with a fixed seed. Everything random in this file uses it.
const rand = mulberry32(20260621);
// Picks a random item from a list.
const pick = (list) => list[Math.floor(rand() * list.length)];
// Random whole number from min to max (both included).
const between = (min, max) => min + Math.floor(rand() * (max - min + 1));
// Returns true with probability p (for example chance(0.2) is true about 20% of the time).
const chance = (p) => rand() < p;
// Random text made of n hex characters (0-9, a-f). Used to make image names and fake device ids unique.
const hex = (n) => Array.from({ length: n }, () => Math.floor(rand() * 16).toString(16)).join('');

